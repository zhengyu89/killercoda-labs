#!/bin/bash
#
# Every exit path below says why. Killercoda only reads the exit code, so the
# explanation is written to /root/.check and the learner reads it with `why`.
LOG=/root/.check
STEP="Step 4 · Pantry credentials"
: > "$LOG"
fail() { { echo "x $STEP"; echo; printf '%s\n' "$@"; } | tee "$LOG"; exit 1; }
pass() { echo "OK $STEP -- passed." | tee "$LOG"; exit 0; }
R=""

NS=pantry
D=pantry-ledger
TOKEN_FILE=/root/pantry/secrets/api-token.txt
WANT_TOKEN=$(cat "$TOKEN_FILE" 2>/dev/null)

for _ in $(seq 1 18); do
  kubectl -n $NS get deploy $D >/dev/null 2>&1 || { R="nodeploy"; sleep 5; continue; }

  ENVREF=$(kubectl -n $NS get deploy $D -o jsonpath='{.spec.template.spec.containers[?(@.name=="ledger")].env[?(@.name=="VENDOR_ID")].valueFrom.secretKeyRef.name}' 2>/dev/null)
  ENVKEY=$(kubectl -n $NS get deploy $D -o jsonpath='{.spec.template.spec.containers[?(@.name=="ledger")].env[?(@.name=="VENDOR_ID")].valueFrom.secretKeyRef.key}' 2>/dev/null)
  [ -n "$ENVREF" ] || { R="noenv"; sleep 5; continue; }
  [ "$ENVREF" != "pantry-creds" ] || { R="handmade"; sleep 5; continue; }
  # The generated name: pantry-creds plus Kustomize's 10-character content hash.
  echo "$ENVREF" | grep -Eq '^pantry-creds-[a-z0-9]{10}$' || { R="notgenerated"; sleep 5; continue; }
  [ "$ENVKEY" == "vendor-id" ] || { R="envkey"; sleep 5; continue; }

  kubectl -n $NS get secret "$ENVREF" >/dev/null 2>&1 || { R="nosecret"; sleep 5; continue; }
  SVID=$(kubectl -n $NS get secret "$ENVREF" -o jsonpath='{.data.vendor-id}' 2>/dev/null | base64 -d 2>/dev/null)
  STOK=$(kubectl -n $NS get secret "$ENVREF" -o jsonpath='{.data.api-token}' 2>/dev/null | base64 -d 2>/dev/null)
  [ "$SVID" == "ORBIT-7731" ] || { R="secretvid"; sleep 5; continue; }
  [ -n "$WANT_TOKEN" ] && [ "$STOK" == "$WANT_TOKEN" ] || { R="secrettok"; sleep 5; continue; }

  VOLS=$(kubectl -n $NS get deploy $D -o jsonpath='{range .spec.template.spec.volumes[*]}{.name}|{.secret.secretName}{"\n"}{end}' 2>/dev/null)
  VOL=$(echo "$VOLS" | awk -F'|' -v s="$ENVREF" '$2==s {print $1; exit}')
  [ -n "$VOL" ] || { R="novol"; sleep 5; continue; }
  MNT=$(kubectl -n $NS get deploy $D -o jsonpath="{.spec.template.spec.containers[?(@.name==\"ledger\")].volumeMounts[?(@.name==\"$VOL\")].mountPath}|{.spec.template.spec.containers[?(@.name==\"ledger\")].volumeMounts[?(@.name==\"$VOL\")].readOnly}" 2>/dev/null)
  [ "$MNT" == "/etc/pantry|true" ] || { R="mount"; sleep 5; continue; }

  # Rollout finished, so the exec below lands on a Pod built from this spec.
  SPEC=$(kubectl -n $NS get deploy $D -o jsonpath='{.spec.replicas}' 2>/dev/null)
  READY=$(kubectl -n $NS get deploy $D -o jsonpath='{.status.readyReplicas}' 2>/dev/null)
  UPD=$(kubectl -n $NS get deploy $D -o jsonpath='{.status.updatedReplicas}' 2>/dev/null)
  TOTAL=$(kubectl -n $NS get deploy $D -o jsonpath='{.status.replicas}' 2>/dev/null)
  [ -n "$SPEC" ] && [ "$READY" == "$SPEC" ] && [ "$UPD" == "$SPEC" ] && [ "$TOTAL" == "$SPEC" ] \
    || { R="notready"; sleep 5; continue; }

  # What the running container actually sees.
  GOT_VID=$(kubectl -n $NS exec deploy/$D -c ledger -- printenv VENDOR_ID 2>/dev/null)
  [ "$GOT_VID" == "ORBIT-7731" ] || { R="podenv"; sleep 5; continue; }
  FILES=$(kubectl -n $NS exec deploy/$D -c ledger -- ls /etc/pantry 2>/dev/null | tr '\n' ' ' | sed 's/ $//')
  [ "$FILES" == "token" ] || { R="podfiles"; sleep 5; continue; }
  GOT_TOK=$(kubectl -n $NS exec deploy/$D -c ledger -- cat /etc/pantry/token 2>/dev/null)
  [ "$GOT_TOK" == "$WANT_TOKEN" ] || { R="podtok"; sleep 5; continue; }
  MODE=$(kubectl -n $NS exec deploy/$D -c ledger -- stat -L -c %a /etc/pantry/token 2>/dev/null)
  [ "$MODE" == "400" ] || { R="podmode"; sleep 5; continue; }

  pass
done

case "$R" in
  nodeploy) fail \
    "There is no Deployment pantry-ledger in namespace pantry yet." \
    "" \
    "Deploy the kustomization (it sets the namespace for you):" \
    "  kubectl apply -k /root/pantry" ;;
  noenv) fail \
    "The ledger container has no VENDOR_ID env var taken from a Secret." \
    "" \
    "It needs env[].valueFrom.secretKeyRef with name pantry-creds and key vendor-id." \
    "Leave the name as plain 'pantry-creds' in your YAML: Kustomize rewrites it." ;;
  handmade) fail \
    "VENDOR_ID refers to a Secret named exactly 'pantry-creds'." \
    "" \
    "That means Kustomize did not generate it -- a secretGenerator Secret gets a" \
    "content hash suffix (pantry-creds-xxxxxxxxxx) and Kustomize rewrites the" \
    "reference to match. Add a secretGenerator to /root/pantry/kustomization.yaml" \
    "and deploy with:" \
    "  kubectl kustomize /root/pantry     # preview" \
    "  kubectl apply -k /root/pantry" ;;
  notgenerated) fail \
    "VENDOR_ID refers to Secret '${ENVREF}', which is not a pantry-creds Secret" \
    "generated by Kustomize." \
    "" \
    "  kubectl kustomize /root/pantry | grep -A3 'kind: Secret'" ;;
  envkey) fail \
    "VENDOR_ID reads key '${ENVKEY}' of the Secret; it should read 'vendor-id'." ;;
  nosecret) fail \
    "The Deployment refers to Secret ${ENVREF}, which does not exist in pantry." \
    "" \
    "Apply the kustomization as a whole so the Secret and the Deployment" \
    "arrive together:" \
    "  kubectl apply -k /root/pantry" ;;
  secretvid) fail \
    "Secret ${ENVREF} has vendor-id='${SVID}', expected ORBIT-7731." \
    "" \
    "  literals:" \
    "  - vendor-id=ORBIT-7731" ;;
  secrettok) fail \
    "Secret ${ENVREF} key api-token does not match /root/pantry/secrets/api-token.txt." \
    "" \
    "Generate it from the file rather than typing the value:" \
    "  files:" \
    "  - api-token=secrets/api-token.txt" ;;
  novol) fail \
    "No volume in pantry-ledger mounts Secret ${ENVREF}." \
    "" \
    "Add a secret volume with secretName: pantry-creds -- Kustomize rewrites" \
    "that name too -- and project the api-token key as 'token'." ;;
  mount) fail \
    "The Secret volume is not mounted read-only at /etc/pantry in container ledger." \
    "" \
    "  found (mountPath|readOnly): ${MNT:-<not mounted>}" ;;
  notready) fail \
    "pantry-ledger has not finished rolling out (ready ${READY:-0} of ${SPEC:-?})." \
    "" \
    "  kubectl -n pantry get pods" \
    "  kubectl -n pantry describe pod -l app=pantry-ledger | grep -A8 Events" ;;
  podenv) fail \
    "Inside the running Pod, VENDOR_ID is '${GOT_VID}', not ORBIT-7731." \
    "" \
    "  kubectl -n pantry exec deploy/pantry-ledger -- printenv VENDOR_ID" ;;
  podfiles) fail \
    "/etc/pantry in the Pod contains '${FILES:-<nothing>}'; it should contain only 'token'." \
    "" \
    "Without items:, every key in the Secret becomes a file. Project just one:" \
    "  items:" \
    "  - key: api-token" \
    "    path: token" ;;
  podtok) fail \
    "/etc/pantry/token in the Pod does not hold the token from api-token.txt." ;;
  podmode) fail \
    "/etc/pantry/token has mode ${MODE:-?} in the Pod; it should be 400." \
    "" \
    "Set defaultMode: 0400 on the volume (or mode: 0400 on the item). In YAML" \
    "the leading 0 matters: 0400 is octal; 400 is decimal and means rw--w----." \
    "  kubectl -n pantry exec deploy/pantry-ledger -- stat -L -c %a /etc/pantry/token" ;;
  *) fail "Unexpected state -- rerun the check." ;;
esac
